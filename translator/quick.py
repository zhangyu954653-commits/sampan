# 泰语句尾的礼貌词 / 语气词，比对时剥掉。按长到短排，先剥长的。
_PARTICLES = ["นะครับ", "นะคะ", "น่ะครับ", "น่ะคะ", "ครับผม", "ค่ะ", "คะ",
              "ครับ", "คับ", "ฮะ", "จ้า", "จ้ะ", "นะ", "น่ะ", "ล่ะ", "ละ"]


def _strip_particles(s: str) -> str:
    """剥掉泰语句尾敬语：ได้ครับ → ได้。剥到不能再剥，但不能剥成空。"""
    changed = True
    while changed:
        changed = False
        for p in _PARTICLES:
            if len(s) > len(p) and s.endswith(p):
                s = s[: -len(p)]
                changed = True
                break
    return s


def lookup(text: str, src: str, tgt: str, gender: str = "") -> str | None:
    """能查表秒回就返回译文，否则返回 None（交给模型正常翻）。"""
    s = normalize(text)
    if not s or len(s) > MAX_LEN.get(src, 12):
        return None

    if src == "zh" and tgt == "th":
        pair = _ZH2TH.get(s) or _ZH2TH.get(_squeeze(s))
        if pair is None:
            return None
        return pair[1] if str(gender).lower() == "female" else pair[0]

    if src == "th" and tgt == "zh":
        # ครับ / ค่ะ 本身就是一句话，别先剥没了
        if s in _TH2ZH:
            return _TH2ZH[s]
        stem = _strip_particles(s)
        return _TH2ZH.get(stem)

    return None
