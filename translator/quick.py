"""口头语处理：该丢的丢掉，该秒回的不走云端。

真实会议记录（819 条字幕）里量出来的问题：
  · ≤8 字的短句占 198 条 ＝ 24%，累计让人干等了 309 秒；
  · 单是"嗯。"就出现 13 次，每次都跑一趟云端识别 + 一趟翻译，
    最后译文还是空的。

所以分两层处理：
  丢弃层  纯语气词（嗯/啊/哦/อืม/เอ่อ…），零信息量，连字幕都不出；
  秒回层  "好的""收到""ครับ""ไม่มี"这类话，查表直接给译文，
          0 毫秒、不花钱、而且同一句话每次译法都一样。

判断一律在**整句**上做，且只对短句生效——绝不能把有内容的话吃掉。
"""
